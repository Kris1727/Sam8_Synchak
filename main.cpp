// **1. Що таке перевантаження функцій і для чого воно використовується?**
// Це можливість мати кілька функцій з однаковим іменем, але з різними списками параметрів (типи або кількість). Компілятор сам обирає потрібну за аргументами виклику. Використовується, щоб одну й ту саму дію (наприклад, `max`) виконувати над різними типами під однією назвою.
//
// **2. Чому перевантаження функцій може призводити до дублювання коду?**
// Кожна перевантажена версія є окремою реалізацією. Якщо алгоритм однаковий (порівняти й повернути більше), тіло копіюється для `int`, `double`, `string` тощо. Зміна алгоритму потребує правок у всіх копіях, що підвищує ризик неузгоджених змін.
//
// **3. Що таке шаблон функції в C++?**
// Це «рецепт» створення функцій: узагальнений опис алгоритму з параметром типу (`template <typename T>`). Сам шаблон не є готовою функцією. Конкретні функції формує компілятор для тих типів, з якими шаблон викликається.
//
// **4. Яку проблему розв'язує шаблон функції порівняно з кількома перевантаженими функціями?**
// Усуває дублювання: один запис замість багатьох майже однакових. Також він автоматично працює з новими типами, які підтримують потрібні операції, без написання додаткових функцій.
//
// **5. Що означає формальний параметр типу в шаблоні?**
// Це ім'я-заповнювач типу (зазвичай `T`) у `template <typename T>`. Фактичний тип підставляється під час виклику або інстанціювання (`T = int`, `T = std::string`).
//
// **6. Як відбувається виклик шаблону функції?**
// Як звичайної функції: `maxValue(7, 5)`. Компілятор виводить `T` з типів аргументів. Тип можна вказати явно: `maxValue<int>(7, 5)`, коли виведення неоднозначне або потрібне певне перетворення.
//
// **7. Чим оголошення шаблону функції відрізняється від його визначення?**
// Оголошення містить лише заголовок (`template <typename T> T f(T);`), визначення додатково має тіло. Для шаблонів тіло має бути доступне компілятору в точці інстанціювання, тому визначення зазвичай розміщують у заголовковому файлі.
//
// **8. Що таке спеціалізація шаблону функції?**
// Окрема реалізація шаблону для конкретного типу. Записується як `template <> T f<Тип>(...)`. Використовується, коли загальна реалізація для цього типу не підходить.
//
// **9. У яких випадках доцільно створювати спеціалізовану версію шаблону?**
// Коли для певного типу потрібна інша поведінка (наприклад, `std::string` не працює з `std::to_string`) або оптимізація. Для функцій часто краще перевантаження, бо спеціалізація не бере участі у виборі перевантаження і може працювати несподівано.
//
// **10. Чим шаблон класу відрізняється від звичайного класу?**
// Параметризований за типами (або константами), тому описує цілу «родину» класів. Тип елементів фіксується під час створення екземпляра: `Array<int>`, `Array<double>`. Це різні типи.
//
// **11. Як створюється екземпляр шаблону класу?**
// Вказанням фактичних параметрів у кутових дужках: `Calculator<int> c{13, 4};`. Компілятор генерує клас для цих параметрів (інстанціювання), причому тільки ті методи, які реально викликаються.
//
// **12. Чому шаблони класів корисні для контейнерів і структур даних?**
// Логіка контейнера (зберігання, вставка, обхід) не залежить від типу елементів. Шаблон описує її один раз для будь-якого типу. Так працюють `std::vector`, `std::array`, `std::map`.
//
// **13. Як визначати методи шаблону класу поза тілом класу?**
// Повторити заголовок шаблону й вказати повне ім'я з параметрами:
// ```cpp
// template <typename T, std::size_t N>
// void FixedBuffer<T, N>::sortAscending() { /* ... */ }
// ```
// Визначення має залишатися у заголовковому файлі.
//
// **14. Що таке дружня функція у контексті шаблону класу?**
// Функція, якій клас надає доступ до приватних членів (`friend`). Для шаблонного класу найчастіше це `operator<<`. Її роблять шаблонною або залежною від `T`, щоб для різних `T` не було конфліктів визначень.
//
// **15. Які особливості має спеціалізація шаблону класу?**
// Вона не є успадкуванням: методи первинного шаблону автоматично не доступні, їх треба оголосити в спеціалізації. Буває повна (усі параметри задані) і часткова (`Formatter<std::vector<T>>`). Первинний шаблон має бути оголошений раніше.
//
// **16. Як шаблон функції може використовуватися як метод шаблону класу?**
// Метод шаблонного класу може мати власні параметри шаблону: `template <typename U, std::size_t M> void assign_from(const StaticArray<U, M>&)`. Параметри класу (`T`, `N`) і методу (`U`, `M`) незалежні.
//
// **17. Що означає передавання шаблону класу як формального параметра?**
// Два випадки. Функція може приймати конкретний екземпляр (`const Repository<T, Storage>&`), а компілятор виведе параметри. Також сам шаблон може бути параметром іншого шаблону (`template <typename...> class Storage`), так вибирають, наприклад, `std::vector` чи `std::list`.
//
// **18. Як шаблони допомагають реалізувати узагальнені алгоритми обробки масивів?**
// Алгоритм (пошук мінімуму, сортування) пишеться для `T`. Вимога лише у наборі операцій над `T` (`<`). Один і той самий код працює для `int`, `double`, `string` і власних класів (див. `task02`, `task08`).
//
// **19. Які оператори потрібно перевантажити для власного класу, якщо його об'єкти використовуються у шаблоні обробки масиву?**
// Ті, що використовує тіло шаблону. Для пошуку мінімуму й максимуму та сортування це `operator<` (інколи `>`, `==`). Для виведення потрібен `operator<<`, для додавання елементів `operator+` або `+=`.
//
// **20. Чому шаблони підвищують повторне використання коду?**
// Один опис працює для багатьох типів без копіювання. Тому на шаблонах побудовано стандартну бібліотеку. Одну перевірену реалізацію використовують у багатьох проєктах.
//
// **21. Які ризики виникають при надмірному використанні шаблонів?**
// Складний код, який важко читати; довгі повідомлення про помилки; збільшення розміру програми та часу компіляції (кожен тип дає окремий екземпляр); прихована залежність від операцій над типом. Шаблон не повинен приховувати логіку програми.
//
// **22. Як шаблони пов'язані з принципом узагальненого програмування?**
// Узагальнене програмування означає писати алгоритми й структури через вимоги до типів, а не через конкретні типи. Шаблони C++ є основним засобом його реалізації (у Java та C# для цього generics).
//
// **23. Чим шаблон відрізняється від макросу?**
// Макрос — текстова підстановка препроцесора без перевірки типів, з побічними ефектами (аргумент може обчислитися двічі) і без областей видимості. Шаблон обробляє компілятор: типобезпечний, має семантику звичайних функцій і класів, зрозуміліші діагностики.
//
// **24. Як компілятор створює конкретну версію шаблону?**
// Бачачи виклик (або використання) з певними типами, компілятор підставляє їх замість `T` у тіло шаблону й компілює отриману функцію чи клас. Це називають інстанціюванням. Створюються тільки реально потрібні екземпляри.
//
// **25. Чому помилки в шаблонах іноді складніше діагностувати?**
// Помилка виникає під час інстанціювання, а не там, де написано шаблон. Повідомлення описує весь ланцюжок («required from here…»), особливо для вкладених шаблонів і стандартної бібліотеки. Допомагають `concepts`, `requires`, `static_assert`.
//
// **26. Як VS Code може допомогти в роботі з шаблонним кодом?**
