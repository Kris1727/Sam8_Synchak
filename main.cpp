namespace task3 {
class Tovar {
private:
    std::string nazva_;
    double tsina_{};

public:
    Tovar(std::string nazva, double tsina)
        : nazva_(std::move(nazva)), tsina_(tsina) {}
    const std::string& nazva() const { return nazva_; }
    double tsina() const { return tsina_; }
    bool operator<(const Tovar& other) const { return tsina_ < other.tsina_; }
};

std::ostream& operator<<(std::ostream& os, const Tovar& t) {
    return os << t.nazva() << " (" << t.tsina() << " грн)";
}

template <typename T>
const T& maxElement(const std::vector<T>& items) {
    std::size_t best = 0;
    for (std::size_t i = 1; i < items.size(); ++i)
        if (items[best] < items[i]) best = i;
    return items[best];
}

void run() {
    std::vector<Tovar> tovary{{"Клавіатура", 1499.50}, {"Монітор", 6500.0}, {"Миша", 520.0}};
    std::vector<int> numbers{3, 17, 5};
    std::cout << "Найдорожчий товар: " << maxElement(tovary) << '\n';
    std::cout << "Найбільше число:   " << maxElement(numbers) << '\n';
}
}  // namespace task3

