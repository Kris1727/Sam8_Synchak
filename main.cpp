namespace task2 {
template <typename T, std::size_t N>
T minInArray(const T (&data)[N]) {
    static_assert(N > 0, "масив не повинен бути порожнім");
    T result = data[0];
    for (std::size_t i = 1; i < N; ++i)
        if (data[i] < result) result = data[i];
    return result;
}

template <typename T>
T minInArray(const T* data, std::size_t size) {
    if (size == 0) throw std::invalid_argument("порожній масив");
    T result = data[0];
    for (std::size_t i = 1; i < size; ++i)
        if (data[i] < result) result = data[i];
    return result;
}

void run() {
    int ints[] = {4, 12, -3, 8, 7};
    double doubles[] = {2.5, 0.75, 9.1, 3.3};
    std::cout << "min(int)     = " << minInArray(ints) << '\n';
    std::cout << "min(double)  = " << minInArray(doubles) << '\n';
    const int* p = ints;
    std::cout << "min(int*, 3) = " << minInArray(p, 3) << '\n';
}
}  // namespace task2

