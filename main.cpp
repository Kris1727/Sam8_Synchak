// **29. Як шаблони функцій і класів можуть бути використані в інформаційних системах?**
// Універсальні репозиторії `Repository<T>` для різних сутностей (товар, клієнт, замовлення); узагальнений пошук і сортування записів; контейнери результатів і пагінація; форматувальники звітів; обгортки відповідей API `Result<T>`. Це зменшує дублювання коду для різних сутностей предметної області.
//
// **30. Які критерії слід застосовувати для вибору між перевантаженням і шаблоном?**
// * Однаковий алгоритм для багатьох типів → **шаблон**.
// * Різна логіка для різних типів → **перевантаження**.
// * Загальний алгоритм і лише один виняток → шаблон плюс перевантаження (або спеціалізація) для винятку.
// * Типів небагато й вони не змінюються, а читабельність важливіша → перевантаження.
// * Тип можна обмежити вимогами (`concept`) → шаблон.
