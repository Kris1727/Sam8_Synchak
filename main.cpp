namespace task5 {
template <typename T>
class Array {
private:
    T* data_;
    std::size_t size_;

public:
    explicit Array(std::size_t size) : data_(new T[size]{}), size_(size) {
        std::cout << "  [ctor] розмір " << size_ << '\n';
    }
    // Глибока копія
    Array(const Array& other) : data_(new T[other.size_]), size_(other.size_) {
        std::copy(other.data_, other.data_ + size_, data_);
        std::cout << "  [copy] розмір " << size_ << '\n';
    }
    // Присвоєння (copy-and-swap)
    Array& operator=(Array other) {
        std::swap(data_, other.data_);
        std::swap(size_, other.size_);
        return *this;
    }
    ~Array() {
        std::cout << "  [dtor] розмір " << size_ << '\n';
        delete[] data_;
    }

    std::size_t size() const { return size_; }
    T& operator[](std::size_t i) { return data_[i]; }
    const T& operator[](std::size_t i) const { return data_[i]; }

    void print() const {
        std::cout << '[';
        for (std::size_t i = 0; i < size_; ++i) {
            std::cout << data_[i];
            if (i + 1 < size_) std::cout << ", ";
        }
        std::cout << "]\n";
    }
};

void run() {
    std::cout << "Створюємо a:\n";
    Array<int> a(3);
    a[0] = 1; a[1] = 2; a[2] = 3;
    std::cout << "Копіюємо в b:\n";
    Array<int> b = a;
    b[0] = 100;
    std::cout << "a = "; a.print();
    std::cout << "b = "; b.print();
    std::cout << "Присвоєння c = a:\n";
    Array<int> c(1);
    c = a;
    std::cout << "c = "; c.print();
    std::cout << "Кінець функції (деструктори):\n";
}
}  // namespace task5

