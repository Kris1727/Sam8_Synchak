// =====================================================================
//
// ## Коротко
//
// | | Перевантаження функції | Спеціалізація шаблону функції |
// |---|---|---|
// | Що це | Кілька **незалежних** функцій з однією назвою, але різними параметрами | Окрема реалізація **того самого шаблону** для конкретного типу |
// | Синтаксис | звичайна функція (або інший шаблон) | `template <> ... name<Тип>(...)` |
// | Хто вибирає | Компілятор за правилами вибору найкращого кандидата | Після вибору шаблону компілятор підставляє спеціалізацію, якщо вона підходить |
// | Бере участь у виборі перевантаження | Так, як повноправний кандидат | Ні: обирається шаблон, а вже потім його спеціалізація |
// | Типова проблема | Дублювання коду | Несподіваний вибір, якщо є ще й перевантаження |
//
// ## Власний приклад (товарний облік)
//
// ```cpp
// #include <iostream>
// #include <string>
//
// // Первинний шаблон
// template <typename T>
// std::string label(const T& v) { return "позиція: " + std::to_string(v); }
//
// // СПЕЦІАЛІЗАЦІЯ шаблону для std::string
// template <>
// std::string label<std::string>(const std::string& v) { return "назва: " + v; }
//
// // ПЕРЕВАНТАЖЕННЯ - окрема звичайна функція для const char*
// std::string label(const char* v) { return std::string("літерал: ") + v; }
//
// int main() {
//     std::cout << label(42) << '\n';                    // шаблон
//     std::cout << label(std::string{"Миша"}) << '\n';   // спеціалізація
//     std::cout << label("Миша") << '\n';                // перевантаження
// }
// ```
//
// Результат:
//
// ```
// позиція: 42
// назва: Миша
// літерал: Миша
// ```
//
// ## Пояснення
//
// * `label(42)`: підходить тільки шаблон, `T = int`.
// * `label(std::string{...})`: компілятор обирає шаблон, потім для `T = std::string` використовується **спеціалізація**.
// * `label("Миша")`: звичайна функція `label(const char*)` підходить краще, ніж шаблон з `T = char[5]`. Це **перевантаження**, і воно перемагає.
//
// ## Практичне правило
//
// Спеціалізація функціонального шаблону не бере участі в розв'язанні перевантажень. Через це інколи працює не так, як очікуєш.
// Тому в лекції радять: для окремої поведінки з певним типом найчастіше простіше й безпечніше написати **перевантажену функцію**, а спеціалізацію використовувати обережно.

