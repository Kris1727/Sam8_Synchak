namespace task4 {
template <typename T>
class Array {
private:
    T* data_;
    std::size_t size_;

public:
    explicit Array(std::size_t size) : data_(new T[size]{}), size_(size) {}
    Array(const Array&) = delete;
    Array& operator=(const Array&) = delete;
    ~Array() { delete[] data_; }

    std::size_t size() const { return size_; }
    T& operator[](std::size_t i) { return data_[i]; }
    const T& operator[](std::size_t i) const { return data_[i]; }

    void print() const {
        std::cout << '[';
        for (std::size_t i = 0; i < size_; ++i) {
            std::cout << data_[i];
            if (i + 1 < size_) std::cout << ", ";
        }
        std::cout << "]\n";
    }
};

void run() {
    Array<int> a(4);
    for (std::size_t i = 0; i < a.size(); ++i) a[i] = static_cast<int>(i * i);
    a.print();
    Array<std::string> s(2);
    s[0] = "Іванна";
    s[1] = "Олег";
    s.print();
}
}  // namespace task4

