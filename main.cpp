// ЗАВДАННЯ 10. Переваги та обмеження шаблонів
// =====================================================================
//
// | Критерій | Шаблони функцій | Шаблони класів |
// |---|---|---|
// | **Призначення** | Один алгоритм для різних типів (`maxValue`, `minInArray`) | Один тип-контейнер або обгортка для різних типів (`Array<T>`, `std::vector<T>`) |
// | **Виведення типів** | Автоматичне з аргументів виклику: `maxValue(3, 5)` | До C++17 тип треба вказувати явно: `Array<int>`. З C++17 є виведення (CTAD) |
// | **Перевага: повторне використання** | Немає дублювання перевантажень | Одна реалізація контейнера для будь-яких елементів |
// | **Перевага: безпека типів** | Перевірка типів під час компіляції (на відміну від макросів) | Те саме, плюс різні екземпляри `Array<int>` і `Array<double>` є різними типами |
// | **Перевага: швидкодія** | Код генерується під конкретний тип, без накладних витрат виконання | Те саме |
// | **Спеціалізація** | Лише повна. Часткової немає, замість неї перевантаження | Повна й часткова (`Formatter<std::vector<T>>`) |
// | **Перевантаження** | Можна, і воно бере участь у виборі кандидата | Неможливе (клас не перевантажується) |
// | **Обмеження: вимоги до T** | Тип має підтримувати операції з тіла (`<`, `+`) | Те саме для кожного методу, який викликається |
// | **Обмеження: розміщення коду** | Визначення має бути видимим при інстанціюванні (зазвичай у `.hpp`) | Те саме. Методи з `.cpp` дають `undefined reference` |
// | **Обмеження: діагностика** | Довгі повідомлення про помилки з ланцюжком інстанціювання | Ще довші для вкладених шаблонів |
// | **Обмеження: розмір коду** | Кожен тип дає окремий екземпляр у програмі | Те саме, зростає розмір бінарного файлу |
// | **Ризик надмірного використання** | Складні сигнатури, важко читати | Дуже складні ієрархії, важко підтримувати |
// | **Засоби покращення** | `concepts`, `requires`, `static_assert` | `concepts`, `requires`, `static_assert` |
// | **Приклад у стандартній бібліотеці** | `std::max`, `std::sort` | `std::vector`, `std::array`, `std::unique_ptr` |
//
// ## Висновок
//
// Шаблони дають безпечне й ефективне узагальнення без дублювання, але вимагають чітко сформульованих вимог до типів. Для цього зручно користуватися `concepts`. Шаблон варто вводити тоді, коли реально є кілька типів, а не «про всяк випадок».

